<?php

/**
 * @file
 * Writes docs/MIGRATION-MAP.md: where each piece of the Drupal 6 site went in this rebuild, with counts on both
 * sides, and one example page of each kind to open side by side. Generated from the schema `d6` and this site,
 * so it stays true after every run.
 *
 * Run: ddev drush php:script scripts/95-map.php
 */

use Drupal\Core\Database\Database;
use Drupal\field\Entity\FieldConfig;
use Drupal\filter\Entity\FilterFormat;
use Drupal\views\Entity\View;

Database::addConnectionInfo('d6', 'default', ['database' => 'd6'] + Database::getConnectionInfo('default')['default']);
$src = Database::getConnection('default', 'd6');
$q = fn(string $sql, array $args = []) => $src->query($sql, $args)->fetchAll(\PDO::FETCH_ASSOC);
$db = \Drupal::database();
$etm = \Drupal::entityTypeManager();

// Where to look: the Coder URLs while the sites are public, else the local ones.
$original = 'https://hobobiker-copy--remotework--rfay.coder.ddev.com';
$rebuild = 'https://hobobiker-d11--remotework--rfay.coder.ddev.com';
$pair = fn(string $path) => "[original]($original/$path) · [Drupal 11]($rebuild/$path)";
$table = function (array $header, array $rows): string {
  $out = '| ' . implode(' | ', $header) . " |\n|" . str_repeat('---|', count($header)) . "\n";
  foreach ($rows as $r) {
    $out .= '| ' . implode(' | ', array_map(fn($c) => str_replace(["|", "\n"], ['\\|', ' '], (string) $c), $r)) . " |\n";
  }
  return $out;
};
$md = [];
$md[] = "# Migration map: hobobiker.com Drupal 6 → Drupal 11\n";
$md[] = "Generated by `scripts/95-map.php` on " . date('Y-m-d') . " from the schema `d6` and this site; do not edit by hand.";
$md[] = "Decisions: `hobobiker-copy/PART3-PLAN.md`. Deliberate differences: `hobobiker-copy/test/playwright/expected-differences.json`.\n";

// Content.
$md[] = "## Content\n";
$rows = [];
$d6types = array_column($q("SELECT IF(type = '', '(none)', type) t, COUNT(*) c, SUM(status) p FROM node GROUP BY t"), NULL, 't');
$d11types = $db->query('SELECT type t, COUNT(*) c, SUM(status) p FROM {node_field_data} GROUP BY type')->fetchAllAssoc('t', \PDO::FETCH_ASSOC);
foreach ($d6types as $t => $r) {
  $to = $t === '(none)' ? 'page' : $t;
  $rows[] = [$t, "$r[c] ($r[p] published)", $to, $t === '(none)' ? 'counted in page' : (($d11types[$to]['c'] ?? 0) . ' (' . ($d11types[$to]['p'] ?? 0) . ' published)')];
}
$md[] = $table(['Drupal 6 type', 'Nodes', 'Drupal 11 type', 'Nodes'], $rows);
$count = fn(string $sql) => $q($sql)[0]['c'];
$md[] = $table(['What', 'Drupal 6', 'Drupal 11', 'Note'], [
  ['Comments', $count('SELECT COUNT(*) c FROM comments'), $db->query('SELECT COUNT(*) FROM {comment_field_data}')->fetchField(), 'one on a deleted node dropped; stored, never shown (comment module off on the original)'],
  ['Terms', $count('SELECT COUNT(*) c FROM term_data'), $db->query('SELECT COUNT(*) FROM {taxonomy_term_field_data}')->fetchField(), ''],
  ['Users', $count('SELECT COUNT(*) c FROM users WHERE uid > 0'), $db->query('SELECT COUNT(*) FROM {users_field_data} WHERE uid > 0')->fetchField(), 'sanitized emails as user+N@example.invalid'],
  ['URL aliases', $count('SELECT COUNT(*) c FROM url_alias'), $db->query('SELECT COUNT(*) FROM {path_alias}')->fetchField(), 'aliases of deleted nodes dropped'],
  ['File records', $count('SELECT COUNT(*) c FROM files'), $db->query('SELECT COUNT(*) FROM {file_managed}')->fetchField(), 'records whose file is gone dropped; every file on disk copied, same URLs'],
  ['Main menu links', $count("SELECT COUNT(*) c FROM menu_links WHERE menu_name = 'menu-menu'"), $db->query("SELECT COUNT(*) FROM {menu_link_content_data} WHERE menu_name = 'main'")->fetchField(), 'menu-menu → main'],
]);

// Fields.
$md[] = "## Fields\n";
$rows = [];
foreach ($q('SELECT i.type_name, i.field_name, i.label, f.type FROM content_node_field_instance i JOIN content_node_field f ON f.field_name = i.field_name ORDER BY i.type_name, i.weight') as $f) {
  $d11 = FieldConfig::loadByName('node', $f['type_name'], $f['field_name']);
  $rows[] = ["$f[type_name].$f[field_name] ($f[type])", $f['label'], $d11 ? "{$f['field_name']} ({$d11->getType()})" : '—'];
}
$rows[] = ['body, teaser (node_revisions)', '', 'body (text_with_summary); the stored teaser is the summary'];
$rows[] = ['audio, audio_metadata (audio module)', '', 'field_audio_* on audio'];
$rows[] = ['poll_choices (poll module)', '', 'field_poll_choices, field_poll_votes on poll'];
foreach ($q('SELECT name FROM vocabulary ORDER BY vid') as $v) {
  $rows[] = ["term_node ($v[name])", '', 'field_' . strtolower(preg_replace('/\W+/', '_', $v['name'])) . ' (entity_reference to terms)'];
}
$md[] = $table(['Drupal 6', 'Label', 'Drupal 11 field'], $rows);

// Text formats.
$md[] = "## Text formats\n";
$used = array_column($q('SELECT r.format, COUNT(*) c FROM node n JOIN node_revisions r ON r.vid = n.vid GROUP BY r.format'), 'c', 'format');
$filters = [];
foreach ($q('SELECT format, module, delta FROM filters ORDER BY format, weight') as $f) {
  $filters[$f['format']][] = "$f[module]/$f[delta]";
}
$byName = [];
foreach (FilterFormat::loadMultiple() as $fmt) {
  $byName[$fmt->label()] = $fmt;
}
$rows = [];
foreach ($q('SELECT format, name FROM filter_formats ORDER BY format') as $f) {
  $d11 = $byName[$f['name']] ?? ($f['name'] === 'PHP code' ? ($byName['Trip tables (was PHP code)'] ?? NULL) : NULL);
  $enabled = $d11 ? implode(', ', array_keys(array_filter($d11->get('filters'), fn($x) => $x['status']))) : '—';
  $rows[] = ["$f[format] $f[name]", $used[$f['format']] ?? 0, implode(', ', $filters[$f['format']] ?? []), $d11 ? $d11->id() : '—', $enabled];
}
$rows[] = ['0 (site default)', $used[0] ?? 0, '= format 1', 'filtered_html', ''];
$md[] = $table(['Drupal 6 format', 'Nodes', 'Drupal 6 filters', 'Drupal 11 format', 'Drupal 11 filters'], $rows);

// Modules.
$md[] = "## What replaced the Drupal 6 modules\n";
$md[] = $table(['Drupal 6', 'Drupal 11'], [
  ['CCK (content), filefield, imagefield', 'core fields'],
  ['imagecache presets 240x180, 180x240, 600x800, 800x600', 'image styles of the same names'],
  ['hobobiker_filter: [hobophoto:] macros', 'hobobiker module: HobophotoFilter (text filter plugin)'],
  ['php filter: tripinfo_table() calls', 'rewritten at import to [tripinfo:START,END]; hobobiker TripinfoTableFilter'],
  ['tripinfo: tripinfo_item/…, tripinfo/…, [multisource:] maps', 'hobobiker: TripinfoController, MultisourceFilter, Leaflet library'],
  ['Views 2 (21 views)', 'Views (50-views.php rebuilds them from their Drupal 6 definitions); date range argument plugin'],
  ['blog module: /blog, /blog/UID, breadcrumb', 'views blog and blog_author; hobobiker BlogBreadcrumbBuilder'],
  ['audio module: tags, downloads, /audio/by', 'fields; hobobiker Audio, AudioController, AudioBreadcrumbBuilder'],
  ['poll module (one closed poll)', 'fields; results rendered by hobobiker'],
  ['panels / page_manager: the home page', 'hobobiker FrontPageController in core layout_threecol_25_50_25'],
  ['lightbox / lightbox2', 'hobobiker lightbox library (overlay, groups, keys)'],
  ['ed_readmore', 'hobobiker ReadMore (inline read-more link)'],
  ['hobo_golden on golden_hour', 'theme hobo_golden on stable9: same markup, same CSS'],
  ['comment (disabled)', 'comments stored, comment field hidden'],
  ['book (one unpublished book)', 'book type without outlines'],
  ['acidfree, image, forum (modules gone)', 'node types of the same names'],
]);

// Listings.
$md[] = "## Listings and pages\n";
$rows = [];
foreach (View::loadMultiple() as $view) {
  foreach ($view->get('display') as $display) {
    $path = $display['display_options']['path'] ?? NULL;
    if ($path && (str_starts_with($view->id(), 'd6_') || in_array($view->id(), ['blog', 'blog_author', 'taxonomy_term']))) {
      $rows[] = ["/$path", 'view ' . $view->id() . " ($display[id])"];
    }
  }
}
foreach (\Drupal::service('router.route_provider')->getAllRoutes() as $name => $route) {
  if (str_starts_with($name, 'hobobiker.')) {
    $rows[] = [$route->getPath(), "route $name"];
  }
}
sort($rows);
$md[] = $table(['Path', 'Drupal 11'], $rows);

// Side by side.
$md[] = "## Side by side\n";
$md[] = "One page of each kind; open both and compare.\n";
$examples = [];
foreach ($q("SELECT n.type, MIN(n.nid) nid FROM node n WHERE n.status = 1 AND n.type <> '' GROUP BY n.type ORDER BY n.type") as $r) {
  $examples[] = ["$r[type] node", "node/$r[nid]"];
}
// Patterns as placeholders: Drupal reads [brackets] in a query string as a quoted identifier.
$first = fn(string $like) => $q('SELECT MIN(n.nid) nid FROM node n JOIN node_revisions r ON r.vid = n.vid WHERE n.status = 1 AND r.body LIKE :l', [':l' => $like])[0]['nid'];
$hobophoto = $first('%[hobophoto:%');
$tripinfo = $first('%tripinfo_table%');
// Published nodes in formats whose Drupal 6 filter has no port (wiki, gmap, email obfuscation): check by eye.
foreach ($q('SELECT n.nid, f.name FROM node n JOIN node_revisions r ON r.vid = n.vid JOIN filter_formats f ON f.format = r.format
  WHERE n.status = 1 AND r.format IN (6, 7, 8) ORDER BY n.nid') as $r) {
  $examples[] = ["format \"$r[name]\" (its filter not ported)", "node/$r[nid]"];
}
$examples = array_merge($examples, [
  ['photos ([hobophoto:], overlay)', "node/$hobophoto"], ['route table (was PHP)', "node/$tripinfo"],
  ['home page (Panels)', ''], ['blog listing', 'blog'], ['one author\'s blog', 'blog/rfay'], ['trip blog (Views)', 'canada_big_trip_blog'],
  ['taxonomy term', 'inuvik_to_ushuaia'], ['trip day', 'tripinfo_item/2006-06-10/2006-05-01/2006-08-24'], ['trip list', 'tripinfo/2006-05-01/2006-08-24'],
  ['table view', 'wp/2003-01-15--2003-04-01'], ['podcasts', 'podcasts'], ['audio browse', 'audio/by/artist'], ['poll', 'node/4291'],
]);
$md[] = $table(['Kind', 'Path', 'Compare'], array_map(fn($e) => [$e[0], '/' . $e[1], $pair($e[1])], $examples));

@mkdir(DRUPAL_ROOT . '/../docs');
file_put_contents(DRUPAL_ROOT . '/../docs/MIGRATION-MAP.md', implode("\n", $md));
print 'Wrote docs/MIGRATION-MAP.md (' . count($examples) . " example pages)\n";
